# -*- coding: utf-8 -*-
"""Учебный пример обработки результатов эксперимента Э1 (раздел 2.5).

ДАННЫЕ ПОРОЖДЕНЫ ГЕНЕРАТОРОМ, А НЕ ИЗМЕРЕНЫ.
Назначение — показать полную цепочку обработки по ГОСТ Р 8.736-2011
на данных с реалистичной структурой: T_о почти равномерно (фаза отказа
внутри цикла опроса), T_р скошено вправо. Зерно зафиксировано.
"""
import numpy as np, math
from scipy import stats

SEED = 20260904
rng = np.random.default_rng(SEED)
n = 30

# T_о: контроллер признаёт узел недостижимым через 50 с (версия 1.32 и новее; ранее 40 с) после ПОСЛЕДНЕГО принятого
# обновления. Момент отказа равномерен внутри 10-секундного цикла публикации,
# проверка контроллером — каждые 5 с. Отсюда T_о = 50 - U(0,10) + U(0,5),
# диапазон 40..55 с, среднее 47,5 с. Документированные 50 с — параметр, не ожидание.
To = 50.0 - rng.uniform(0, 10, n) + rng.uniform(0, 5, n) + rng.normal(0, 0.15, n)
# T_п1: ожидание перед вытеснением 300 с + выбор узла
Tp1 = 300.0 + rng.gamma(2.0, 0.35, n)
# T_п2: запуск процесса при предзагруженном образе. Согласовано с SLO проекта
# платформы [55]: 99-й процентиль запуска <= 5 с. Медиана 2,0 с, sigma 0,35 -> p99 = 4,5 с.
Tp2 = rng.lognormal(mean=math.log(2.0), sigma=0.35, size=n)
# T_п3: приведение в готовность. Нормативом [55] НЕ охватывается: SLI доведён
# до момента «контейнеры запущены», а не «готов к обслуживанию».
Tp3 = rng.lognormal(mean=math.log(9.0), sigma=0.25, size=n)
# T_р: перенаправление ШТАТНЫМ механизмом платформы — путь через интерфейс
# управления (запрос -> запись в хранилище состояния -> рассылка -> применение
# правил на узлах). Порядок согласован с главой 3: принятая в расчётах оценка
# 1 с (раздел 3.2), измеренное в Э1 значение 1,12 с (таблица 3.6).
# НЕ путать с T_р предлагаемого метода (около 1,6 мс, раздел 3.5).
Tr = rng.lognormal(mean=math.log(0.9435), sigma=0.45, size=n)

LAM_I, LAM_M = 2000.0, 1000.0
Tr_meas = Tr + rng.uniform(0, 1/LAM_I, n) + rng.uniform(0, 1/LAM_I, n)  # две границы
To_meas = To + rng.uniform(0, 1/LAM_M, n)                              # маяк

def grubbs(x, alpha=0.05):
    x = np.asarray(x, float); N = len(x)
    G = np.max(np.abs(x - x.mean()))/x.std(ddof=1)
    t = stats.t.ppf(1 - alpha/(2*N), N-2)
    Gcr = (N-1)/math.sqrt(N)*math.sqrt(t**2/(N-2+t**2))
    return G, Gcr, G > Gcr

def shapiro(x):
    W, p = stats.shapiro(x); return W, p

def report(name, x, unit, scale=1.0):
    x = np.asarray(x, float)*scale
    W, p = shapiro(x)
    normal = p > 0.05
    G, Gcr, out = grubbs(x)
    print(f'\n--- {name} ({unit}) ---')
    print(f'  n={len(x)}  среднее={x.mean():.4g}  медиана={np.median(x):.4g}  s={x.std(ddof=1):.4g}  V={x.std(ddof=1)/x.mean():.3f}')
    print(f'  Шапиро-Уилка: W={W:.4f}, p={p:.4f} -> распределение {"нормальное" if normal else "НЕ нормальное"}')
    if normal:
        print(f'  Граббс: G={G:.3f}, Gкр={Gcr:.3f} -> {"есть выброс" if out else "выбросов нет"}')
        t = stats.t.ppf(0.975, len(x)-1)
        eps = t*x.std(ddof=1)/math.sqrt(len(x))
        print(f'  ПОРЯДОК: параметрический. t={t:.3f}, ДИ = {x.mean():.4g} ± {eps:.4g}  ({eps/x.mean():.2%})')
        return x.mean(), eps, 'параметрический'
    else:
        xs = np.sort(x); lo, hi = xs[9], xs[20]   # ранги 10 и 21, охват 0,957
        print(f'  Граббс неприменим (нормальность не подтверждена)')
        print(f'  ПОРЯДОК: непараметрический. медиана={np.median(x):.4g}, ДИ=[{lo:.4g}; {hi:.4g}] (P=0,957)')
        return np.median(x), (hi-lo)/2, 'непараметрический'

print('='*70); print(f'ПРИМЕР ОБРАБОТКИ Э1.1  (зерно {SEED}, n={n}) — ДАННЫЕ ПОРОЖДЕНЫ'); print('='*70)
print('\n>>> без поправок')
report('T_о измеренное', To_meas, 'с')
report('T_р измеренное', Tr_meas, 'мс', 1e3)

print('\n>>> с поправками (2.4) и (2.5)')
To_c = To_meas - 1/(2*LAM_M)
Tr_c = Tr_meas - 1/LAM_I
m_To, e_To, p_To = report('T_о с поправкой', To_c, 'с')
m_Tp1, e_Tp1, _  = report('T_п1', Tp1, 'с')
m_Tp2, e_Tp2, _  = report('T_п2 запуск', Tp2, 'с')
m_Tp3, e_Tp3, _  = report('T_п3 готовность', Tp3, 'с')
m_Tr, e_Tr, p_Tr = report('T_р с поправкой', Tr_c, 'мс', 1e3)

Tv = To_c + Tp1 + Tp2 + Tp3
m_Tv, e_Tv, _ = report('T_в', Tv, 'с')

print('\n' + '='*70); print('ПРОВЕРКА УСЛОВИЯ ОПРОВЕРЖЕНИЯ ГИПОТЕЗЫ'); print('='*70)
share = (Tp2 + Tp3)/Tv
print(f'  доля (T_п2+T_п3)/T_в: среднее {share.mean():.4f}, макс по опытам {share.max():.4f}')
t = stats.t.ppf(0.975, n-1); eps = t*share.std(ddof=1)/math.sqrt(n)
print(f'  ДИ доли: {share.mean():.4f} ± {eps:.4f}  -> верхняя граница {share.mean()+eps:.4f}')
print(f'  порог 0,5 -> гипотеза {"ОТВЕРГАЕТСЯ" if share.mean()+eps > 0.5 else "НЕ отвергается"}')

print('\n' + '='*70); print('СМЕЩЕНИЕ ОТ ДИСКРЕТНОСТИ (что дают поправки)'); print('='*70)
print(f'  T_р: без поправки {Tr_meas.mean()*1e3:.4f} мс, с поправкой {Tr_c.mean()*1e3:.4f} мс, '
      f'истинное {Tr.mean()*1e3:.4f} мс')
print(f'       смещение без поправки {(Tr_meas.mean()-Tr.mean())*1e6:.0f} мкс = {1/LAM_I*1e6:.0f} мкс ожидаемо')
print(f'  T_о: без поправки {To_meas.mean():.4f} с, с поправкой {To_c.mean():.4f} с, истинное {To.mean():.4f} с')

print('\n' + '='*70)
print('РАЗРЕШАЮЩАЯ СПОСОБНОСТЬ ПРИ ЗНАЧЕНИЯХ T_р ПРЕДЛАГАЕМОГО МЕТОДА')
print('='*70)
# тип B, единичное измерение T_р — по таблице 2.6: T_р вычисляется по (2.4а) из T_в и T_о,
# поэтому складываются их бюджеты: u(T_в) — две дискретности потока запросов,
# u(T_о) — дискретность маяка и рассогласование часов (граница 500 мкс)
CLOCK_BOUND = 500e-6
u_Tv = math.sqrt(2)/(LAM_I*math.sqrt(12))                          # 204 мкс
u_To = math.hypot(1/(LAM_M*math.sqrt(12)), CLOCK_BOUND/math.sqrt(3))  # 408 мкс
uB1 = math.hypot(u_Tv, u_To)                                        # 456 мкс
print(f'  u(T_в) = {u_Tv*1e6:.0f} мкс, u(T_о) = {u_To*1e6:.0f} мкс, u(T_р) = {uB1*1e6:.0f} мкс')
for T in (1.6e-3, 1.12):
    print(f'  T_р = {T*1e3:8.2f} мс: смещение (2.4) = {1/LAM_I/T:6.1%} измеряемой величины; '
          f'тип B единичного = {uB1/T:6.2%}, среднего по {n} = {uB1/math.sqrt(n)/T:6.3%}')
